"""Car selection icons: reads the game's Icon.jpg of every car and writes ../source/carimgs.h
(ARGB1555, bit 15 = opaque): big 128x53 (picture next to the stats) and small 64x27 (scrolling strip).
Usage: python3 build_car_icons.py <folder with the car folders>"""
import os, sys, numpy as np
from PIL import Image
ORDER = [("Roamer", "Roamer"), ("Malice", "Malice"), ("Nevada", "Nevada"), ("Insetta", "Insetta"),
         ("Bullet GT", "Bullet GT"), ("Canyon", "Canyon"), ("Truck", "Truck"), ("Flatmobile", "Flatmobile")]
SIZES = {"Big": (128, 53), "Small": (64, 27)}

def prep(img, w, h):
    # drop the golden frame of the picture, keep the whole car (fit inside, dark padding) and resample
    W, H = img.size
    img = img.crop((int(W * .05), int(H * .06), W - int(W * .05), H - int(H * .05)))
    W, H = img.size
    k = min(w / W, h / H); nw, nh = max(1, int(W * k)), max(1, int(H * k))
    img = img.resize((nw, nh), Image.LANCZOS)
    out = Image.new("RGB", (w, h), (30, 30, 32)); out.paste(img, ((w - nw) // 2, (h - nh) // 2))
    return out

def to555(img):
    a = np.asarray(img.convert("RGB")).astype(np.uint16)
    return (0x8000 | (a[..., 0] >> 3) | ((a[..., 1] >> 3) << 5) | ((a[..., 2] >> 3) << 10)).flatten()

def main(src, out):
    s = "/* AUTO-GENERATED by tools/build_car_icons.py - ARGB1555 car icons (bit 15 = opaque). */\n#pragma once\n"
    for key, (w, h) in SIZES.items():
        s += "#define CARIMG%s_W %d\n#define CARIMG%s_H %d\n" % (key.upper(), w, key.upper(), h)
        s += "static const unsigned short imgCar%s[8][%d] __attribute__((aligned(4))) = {\n" % (key, w * h)
        for folder, name in ORDER:
            im = Image.open(os.path.join(src, folder, name + " Icon.jpg"))
            flat = to555(prep(im, w, h))
            s += "{\n" + "".join("  " + ",".join("0x%04X" % v for v in flat[i:i + 16]) + ",\n" for i in range(0, len(flat), 16)) + "},\n"
        s += "};\n"
    open(out, "w").write(s)
    print("wrote", out, len(s))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/fcars/FLATOUTDSCARS", os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "source", "carimgs.h"))
