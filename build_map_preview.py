#!/usr/bin/env python3
"""Makes mappics.h: the picture shown on the SELECT TRACK screen (104x52, 15-bit colour).
   usage:  python3 build_map_preview.py forest  picture.png
   Any picture works (it is cropped to 2:1 and shrunk).  Only the FOREST card has a picture so far;
   add another name + array in mappics.h and one line in hudMaps() (main.c) for more maps."""
import sys, numpy as np
from PIL import Image, ImageEnhance
W, H = 104, 52
name = sys.argv[1] if len(sys.argv) > 1 else 'forest'
src = Image.open(sys.argv[2] if len(sys.argv) > 2 else 'forest_preview_src.png').convert('RGB')
w, h = src.size
if w * H > h * W:                                   # crop to 2:1
    nw = h * W // H; src = src.crop(((w - nw) // 2, 0, (w + nw) // 2, h))
else:
    nh = w * H // W; src = src.crop((0, (h - nh) // 2, w, (h + nh) // 2))
src = src.resize((W * 4, H * 4), Image.LANCZOS).resize((W, H), Image.BOX)
src = ImageEnhance.Contrast(src).enhance(1.12)
a = np.asarray(src, dtype=np.float32)
bayer = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], np.float32) / 16.0 - 0.5
out = []
for y in range(H):
    for x in range(W):
        px = [int(min(31, max(0, round(a[y, x, c] / 255.0 * 31 + bayer[y % 4, x % 4] * 0.9)))) for c in range(3)]
        out.append(px[0] | (px[1] << 5) | (px[2] << 10))
with open('mappics.h', 'w') as f:
    f.write('/* generated by build_map_preview.py - picture of the map on the SELECT TRACK screen */\n#pragma once\n')
    f.write('#define MAPPIC_W %d\n#define MAPPIC_H %d\n' % (W, H))
    f.write('static const unsigned short mapPic_%s[%d] __attribute__((aligned(4))) = {\n' % (name, W * H))
    for i in range(0, len(out), 16):
        f.write('  ' + ','.join('0x%04x' % v for v in out[i:i + 16]) + ',\n')
    f.write('};\n')
Image.fromarray(np.array([[((v & 31) << 3, ((v >> 5) & 31) << 3, ((v >> 10) & 31) << 3) for v in out[y*W:(y+1)*W]] for y in range(H)], np.uint8)).resize((W*4, H*4), Image.NEAREST).save('mappic_preview.png')
print('ok')
